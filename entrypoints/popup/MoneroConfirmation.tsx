import type { TransactionStatus } from '../../lib/wallet/transactionStatus';

export default function MoneroConfirmation({
  network,
  status,
}: {
  network: string;
  status?: TransactionStatus | null;
}) {
  const confirmations = status?.confirmations;
  return (
    <div className="hint">
      {status?.state === 'confirmed' ? null : status?.state === 'pool' ? (
        <p>Waiting for a miner to include it in a block. Do not send it again.</p>
      ) : (
        <p>An unknown status is not a failed payment. Do not send it again.</p>
      )}
      {network === 'regtest' && status?.state !== 'confirmed' ? (
        <p>
          Local test network: Waiting alone will not confirm the payment if mining is stopped.
          Generate test blocks to advance confirmations.
        </p>
      ) : null}
      <details>
        <summary>About confirmations</summary>
        {status?.state === 'confirmed' ? (
          <p>
            Included in a block
            {confirmations === undefined ? '' : ` · ${confirmations} confirmations`}. Block
            inclusion is not irreversible finality.
          </p>
        ) : (
          <p>
            Relay does not confirm block inclusion. Status is checked automatically with your
            selected daemon.
          </p>
        )}
        {network === 'regtest' ? (
          <p>Blocks on this local test network are generated by the test setup.</p>
        ) : (
          <p>
            Monero targets one block about every 2 minutes, but inclusion can take longer. A
            recipient's wallet usually needs about 10 blocks, roughly 20 minutes on average, before
            normal outputs become spendable. Extra locks or network delays can take longer.
          </p>
        )}
        <p>This payment remains in Monero's Outgoing Activity after leaving this screen.</p>
      </details>
    </div>
  );
}
